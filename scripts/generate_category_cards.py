def write_archive_page(cat_name, cat_label, posts):
    archive_dir = BLOG_DIR / cat_name / "archive"
    archive_dir.mkdir(parents=True, exist_ok=True)
    archive_index = archive_dir / "index.html"

    cards = "\n".join(render_card(p) for p in posts)
    html = ARCHIVE_TEMPLATE.format(
        label=cat_label, label_lower=cat_label.lower(), cat_name=cat_name,
        total=len(posts), cards=cards,
    )
    existing = archive_index.read_text(encoding="utf-8") if archive_index.exists() else None
    archive_index.write_text(html, encoding="utf-8")
    return existing != html


def main():
    any_changed = False
    for cat_name, (cat_label, cap) in CATS.items():
        cat_dir = BLOG_DIR / cat_name
        posts = find_posts(cat_dir, cat_label)
        kept = posts if cap is None else posts[:cap]
        dropped = [] if cap is None else posts[cap:]

        page_changed = update_category_page(cat_name, cat_label, cap, posts)
        archive_changed = write_archive_page(cat_name, cat_label, posts)
        any_changed = any_changed or page_changed or archive_changed

        print(f"\n=== {cat_label} (cap {cap}) ===")
        print(f"Found {len(posts)} posts total. Showing {len(kept)} on category page.")
        for p in kept:
            print(f"  KEPT    {p['date']}  {p['headline']}")
        for p in dropped:
            print(f"  DROPPED {p['date']}  {p['headline']} (still in archive)")
        print(f"blog/{cat_name}/index.html {'changed' if page_changed else 'unchanged'}.")
        print(f"blog/{cat_name}/archive/index.html {'changed' if archive_changed else 'unchanged'}.")

    return 0 if True else 1


if __name__ == "__main__":
    sys.exit(main())
