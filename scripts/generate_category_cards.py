def write_paginated_pages(cat_name, cat_label, posts):
    """Write /blog/<cat>/page/N/ for posts beyond PAGE_SIZE. No-op today
    (no category exceeds PAGINATE_THRESHOLD); exists so a category that
    grows past it gets real indexable pages instead of a noindex archive."""
    if len(posts) <= PAGINATE_THRESHOLD:
        return []

    overflow = posts[PAGE_SIZE:]
    chunks = [overflow[i:i + PAGE_SIZE] for i in range(0, len(overflow), PAGE_SIZE)]
    page_count = 1 + len(chunks)
    written = []

    for i, chunk in enumerate(chunks):
        page_num = i + 2
        page_dir = BLOG_DIR / cat_name / "page" / str(page_num)
        page_dir.mkdir(parents=True, exist_ok=True)
        items = "\n".join(
            f'        <li><a href="{p["url"]}">{p["headline"]}</a> &mdash; {p["description"]}</li>'
            for p in chunk
        )
        prev_num = page_num - 1
        prev_url = f"/blog/{cat_name}/" if prev_num == 1 else f"/blog/{cat_name}/page/{prev_num}/"
        prev_link = f'        <a href="{prev_url}">&larr; Newer {cat_label}</a>\n'
        next_link = ""
        if page_num < page_count:
            next_link = f'        <a href="/blog/{cat_name}/page/{page_num + 1}/">Older {cat_label} &rarr;</a>\n'

        html = PAGE_TEMPLATE.format(
            label=cat_label, label_lower=cat_label.lower(), cat_name=cat_name,
            page_num=page_num, page_count=page_count, items=items,
            prev_link=prev_link, next_link=next_link, SITE=SITE,
        )
        page_index = page_dir / "index.html"
        existing = page_index.read_text(encoding="utf-8") if page_index.exists() else None
        page_index.write_text(html, encoding="utf-8")
        written.append(page_index)
        if existing != html:
            print(f"WROTE {page_index.relative_to(REPO_ROOT)}")

    return written


def main():
    any_changed = False
    for cat_name, (cat_label, cap) in CATS.items():
        cat_dir = BLOG_DIR / cat_name
        ascending = cat_name in ASCENDING_CATS
        posts = find_posts(cat_dir, cat_label, ascending)

        page_changed = update_category_page(cat_name, cat_label, cap, posts)
        write_paginated_pages(cat_name, cat_label, posts)
        any_changed = any_changed or page_changed

        split = cap is not None and len(posts) > cap
        kept = posts[:cap] if split else posts
        print(f"\n=== {cat_label} (featured cap {cap}) ===")
        print(f"Found {len(posts)} posts total. Featured row shows {len(kept)}; full list shows all {len(posts)}.")
        print(f"blog/{cat_name}/index.html {'changed' if page_changed else 'unchanged'}.")

    return 0 if True else 1


if __name__ == "__main__":
    sys.exit(main())
