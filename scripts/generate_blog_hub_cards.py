#!/usr/bin/env python3
"""
Regenerate the Blog Hub's "Latest Posts" card row from the posts actually
on disk, same philosophy as scripts/generate_sitemap.py: the filesystem is
the source of truth, so this can't drift from CONTENT-INDEX.md.

Caps at MAX_CARDS most recent posts (by Article schema datePublished).
Once more than MAX_CARDS posts exist, the oldest drops off automatically
to make room for the newest, keeping blog/index.html on a fixed rotation
instead of growing forever.

Also renders a nav note below the card row (real total post count across
every category, a rotation notice, and a link to /blog/archive/, the
site-wide archive listing every post ever published) and regenerates that
archive page itself. Same mechanic as scripts/generate_category_cards.py,
just at the whole-site level instead of per-category. Added 2026-08-16
after Charlie asked how a visitor reaches a post that's rotated off the
Hub — the per-category archives already covered that, but the Hub itself
had no equivalent "browse everything" link of its own.

Only touches the block between the LATEST-POSTS-START/END markers in
blog/index.html, plus fully (re)writes blog/archive/index.html.
Everything else on the Hub page (hero, category grid, footer) is left
untouched.

Run manually with: python3 scripts/generate_blog_hub_cards.py
Also run automatically on every push to main via
.github/workflows/update-sitemap.yml, alongside the sitemap generator.
"""
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BLOG_DIR = REPO_ROOT / "blog"
BLOG_INDEX = BLOG_DIR / "index.html"
ARCHIVE_INDEX = BLOG_DIR / "archive" / "index.html"
MAX_CARDS = 9

START_MARKER = "<!-- LATEST-POSTS-START: auto-generated by scripts/generate_blog_hub_cards.py, do not hand-edit inside these markers -->"
END_MARKER = "<!-- LATEST-POSTS-END -->"


def find_posts():
    posts = []
    for cat_dir in sorted(p for p in BLOG_DIR.iterdir() if p.is_dir()):
        for post_dir in sorted(p for p in cat_dir.iterdir() if p.is_dir()):
            if post_dir.name == "archive":
                continue
            post_index = post_dir / "index.html"
            if not post_index.exists():
                continue
            html = post_index.read_text(encoding="utf-8")

            headline = _extract(r'"headline":\s*"([^"]*)"', html)
            date_published = _extract(r'"datePublished":\s*"([^"]*)"', html)
            description = _extract(r'<meta name="description" content="([^"]*)"', html)
            img_block = _extract(r'class="post-featured-img"(.*?)>', html, flags=re.S)
            src = _extract(r'src="([^"]*)"', img_block or "")
            height = _extract(r'height="(\d+)"', img_block or "")
            alt = _extract(r'alt="([^"]*)"', img_block or "")

            if not all([headline, date_published, description, src, height, alt]):
                print(f"WARNING: skipping {post_index}, missing required field(s)", file=sys.stderr)
                continue

            base = re.sub(r"-1200w\.jpg$", "", Path(src).name)
            thumb_height = round(int(height) * 400 / 1200)

            posts.append({
                "headline": headline,
                "date": date_published,
                "description": description,
                "base": base,
                "thumb_height": thumb_height,
                "alt": alt,
                "category": cat_dir.name.capitalize(),
                "url": f"/blog/{cat_dir.name}/{post_dir.name}/index.html",
            })
    posts.sort(key=lambda p: p["date"], reverse=True)
    return posts


def _extract(pattern, text, flags=0):
    m = re.search(pattern, text, flags)
    return m.group(1) if m else None


def render_card(p):
    base, cat, url = p["base"], p["category"], p["url"]
    return f'''        <div class="card post-card">
          <picture>
            <source type="image/webp" srcset="/images/blog/srcset/{base}-400w.webp 400w, /images/blog/srcset/{base}-800w.webp 800w" sizes="(max-width: 700px) 100vw, 33vw">
            <img class="post-thumb" src="/images/blog/srcset/{base}-400w.jpg"
              srcset="/images/blog/srcset/{base}-400w.jpg 400w, /images/blog/srcset/{base}-800w.jpg 800w"
              sizes="(max-width: 700px) 100vw, 33vw" width="400" height="{p['thumb_height']}" loading="lazy"
              alt="{p['alt']}">
          </picture>
          <div class="post-card-body">
            <span class="post-cat">{cat}</span>
            <h3>{p['headline']}</h3>
            <p>{p['description']}</p>
            <a class="cta" href="{url}">Read post</a>
          </div>
        </div>'''


def render_note(total, kept_count):
    if total > MAX_CARDS:
        status = (f"<p>Showing the {kept_count} most recent posts, out of "
                   f"<strong>{total} total</strong> across every category. Cards rotate "
                   f"automatically as new posts are added, oldest off, newest on.</p>")
    else:
        status = f"<p>All <strong>{total} posts</strong> are shown below.</p>"
    return f'''<div class="category-note">
        {status}
        <p><a class="btn-secondary" href="/blog/archive/index.html">Browse the Full Blog Archive →</a></p>
      </div>'''


