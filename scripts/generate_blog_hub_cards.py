def write_archive_page(posts):
    ARCHIVE_INDEX.parent.mkdir(parents=True, exist_ok=True)
    cards = "\n".join(render_card(p) for p in posts)
    html = ARCHIVE_TEMPLATE.format(total=len(posts), cards=cards)
    existing = ARCHIVE_INDEX.read_text(encoding="utf-8") if ARCHIVE_INDEX.exists() else None
    ARCHIVE_INDEX.write_text(html, encoding="utf-8")
    return existing != html


def main():
    posts = find_posts()

    kept = posts[:MAX_CARDS]
    dropped = posts[MAX_CARDS:]

    grid = "\n      <div class=\"post-grid\">\n" + "\n".join(render_card(p) for p in kept) + "\n      </div>\n      "
    note = render_note(len(posts), len(kept))
    new_block = START_MARKER + grid + note + "\n      " + END_MARKER

    html = BLOG_INDEX.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START_MARKER) + r".*?" + re.escape(END_MARKER), re.S)
    if not pattern.search(html):
        print("ERROR: LATEST-POSTS markers not found in blog/index.html", file=sys.stderr)
        return 1

    new_html = pattern.sub(lambda _: new_block, html, count=1)
    hub_changed = new_html != html
    BLOG_INDEX.write_text(new_html, encoding="utf-8")

    archive_changed = write_archive_page(posts)

    print(f"Found {len(posts)} posts total. Showing {len(kept)} (cap {MAX_CARDS}).")
    for p in kept:
        print(f"  KEPT    {p['date']}  {p['headline']}")
    for p in dropped:
        print(f"  DROPPED {p['date']}  {p['headline']} (still in archive)")
    print("blog/index.html changed." if hub_changed else "blog/index.html unchanged.")
    print("blog/archive/index.html changed." if archive_changed else "blog/archive/index.html unchanged.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
